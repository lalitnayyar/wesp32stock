#!/usr/bin/env python3
"""Generate derived shared artifacts from the single sources of truth.

  shared/fixtures/dashboard_3page.json   <- backend page builder + shared/fixtures/portfolio_fixture.json
  shared/fixtures/dashboard_3page_<build>.json  <- same, for each 4.2in landscape panel build
  shared/glcdfont.json                   <- Adafruit GFX glcdfont.c (classic 5x7 font) for the browser simulator
  firmware/LalitStockFirmware/shared_contract.h <- device_config.json, panel_profiles.json, layout.json

Usage:  backend/.venv/Scripts/python tools/gen_shared.py [--font PATH_TO_glcdfont.c] [--check]
--check exits 1 if any generated file is out of date (used by tests/CI).

Owner: Lalit Nayyar <consult@lalit.cloud>. Not financial advice.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared"
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("SCHEDULER_ENABLED", "false")


def _profiles() -> dict:
    return json.loads((SHARED / "panel_profiles.json").read_text(encoding="utf-8"))["profiles"]


def _builds() -> list[tuple[str, dict]]:
    """Real (firmware-buildable) panel profiles, in file order."""
    return [(name, p) for name, p in _profiles().items() if p.get("build")]


def gen_fixture(panel_profile: str | None = None) -> str:
    from app.services.dashboard import build_dashboard

    src = json.loads((SHARED / "fixtures" / "portfolio_fixture.json").read_text(encoding="utf-8"))
    dash = build_dashboard(summary=src["summary"], bench_rows=src["benchmarks"], display=src["display"],
                           device_uid=src["device"]["id"], device_name=src["device"]["name"], tz=src["tz"],
                           provider="fixture", now=datetime.fromisoformat(src["generated_at"].replace("Z", "+00:00")),
                           panel_profile=panel_profile)
    dash["status"]["fixture"] = True
    return json.dumps(dash, ensure_ascii=True, separators=(",", ":")) + "\n"


def gen_font(font_c: Path | None) -> str | None:
    target = SHARED / "glcdfont.json"
    if font_c is None or not font_c.exists():
        return target.read_text(encoding="utf-8") if target.exists() else None
    text = font_c.read_text(encoding="utf-8", errors="replace")
    body = text[text.index("font[] PROGMEM = {") if "font[] PROGMEM = {" in text else text.index("font[]"):]
    body = body[body.index("{") + 1: body.index("};")]
    body = re.sub(r"//[^\n]*", "", body)
    data = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", body)]
    if len(data) != 256 * 5:
        raise SystemExit(f"unexpected glcdfont size {len(data)}")
    return json.dumps({"$comment": "Adafruit GFX classic 5x7 font (BSD license, Adafruit Industries); 5 column bytes per glyph, LSB = top row. Generated by tools/gen_shared.py.",
                       "glyph_w": 5, "glyph_h": 8, "data": data}) + "\n"


def _cstr(s: str) -> str:
    return json.dumps(s)


def gen_header() -> str:
    cfg = json.loads((SHARED / "device_config.json").read_text(encoding="utf-8"))["fields"]
    prof = json.loads((SHARED / "panel_profiles.json").read_text(encoding="utf-8"))
    out = ["// GENERATED by tools/gen_shared.py from shared/*.json - DO NOT EDIT.",
           "// Lalit Stock Application - Owner: Lalit Nayyar <consult@lalit.cloud>. Not financial advice.",
           "#pragma once", "#include <stdint.h>", ""]
    out.append("// ---- device configuration defaults / ranges (shared/device_config.json)")
    for name, f in cfg.items():
        up = name.upper()
        if f["type"] == "int":
            out += [f"#define CFG_{up}_DEFAULT {f['default']}", f"#define CFG_{up}_MIN {f['min']}",
                    f"#define CFG_{up}_MAX {f['max']}"]
        elif f["type"] == "bool":
            out.append(f"#define CFG_{up}_DEFAULT {'true' if f['default'] else 'false'}")
        else:
            out.append(f"#define CFG_{up}_DEFAULT {_cstr(f['default'])}")
            if "max_len" in f:
                out.append(f"#define CFG_{up}_MAXLEN {f['max_len']}")
    out += ["", "// ---- panel refresh profiles (shared/panel_profiles.json)",
            "struct PanelProfile { const char* name; const char* label; uint32_t full_refresh_ms; uint16_t safety_margin_pct; uint16_t min_dwell_s; bool verified; bool simulation_only; };",
            f"#define PANEL_FALLBACK_S {prof['fallback_s']}",
            "static const PanelProfile PANEL_PROFILES[] = {"]
    for name, p in prof["profiles"].items():
        out.append(f"  {{{_cstr(name)}, {_cstr(p['label'])}, {p['full_refresh_ms']}, {p['safety_margin_pct']}, "
                   f"{p['min_dwell_s']}, {'true' if p['verified'] else 'false'}, {'true' if p['simulation_only'] else 'false'}}},")
    out += ["};", f"#define PANEL_PROFILE_COUNT {len(prof['profiles'])}", "",
            "// ---- panel selection (compile time): build with -DLS_PANEL=LS_PANEL_<BUILD> (flash.bat COMx <build>).",
            "// Each panel brings its layout (shared/layout*.json) and palette (K black, W white, R red, Y yellow)."]
    builds = _builds()
    for i, (name, p) in enumerate(builds, 1):
        out.append(f"#define LS_PANEL_{p['build'].upper()} {i}  // {name}")
    out += ["#ifndef LS_PANEL", f"#define LS_PANEL LS_PANEL_{builds[0][1]['build'].upper()}", "#endif"]
    for i, (name, p) in enumerate(builds):
        lay = json.loads((SHARED / p["layout"]).read_text(encoding="utf-8"))
        out.append(f"{'#if' if i == 0 else '#elif'} LS_PANEL == LS_PANEL_{p['build'].upper()}")
        out += [f"#define LS_PANEL_PROFILE {_cstr(name)}", f"#define LS_PANEL_BUILD {_cstr(p['build'])}",
                f"#define L_PALETTE {_cstr(p['palette'])}", f"#define L_ID {_cstr(lay['id'])}"]
        out += [f"#define L_C_{role.upper()} '{c}'" for role, c in prof["palette_roles"][p["palette"]].items()]
        flat = {"WIDTH": lay["width"], "HEIGHT": lay["height"], "CHAR_W": lay["char_w"], "CHAR_H": lay["char_h"],
                "MARGIN_X": lay["margin_x"], "BODY_TOP": lay["body"]["top"], "BODY_BOTTOM": lay["body"]["bottom"],
                "FOOTER_SEP_Y": lay["footer"]["sep_y"], "FOOTER_TEXT_Y": lay["footer"]["text_y"]}
        for k, v in lay["header"].items():
            if isinstance(v, int):
                flat[f"HDR_{k.upper()}"] = v
        for k, v in lay["limits"].items():
            flat[f"LIM_{k.upper()}"] = v
        out += [f"#define L_{k} {v}" for k, v in flat.items()]
        out.append(f"#define L_HDR_TITLE {_cstr(lay['header']['title'])}")
    out += ["#else", '#error "Unknown LS_PANEL: use one of the LS_PANEL_* values above"', "#endif"]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", type=Path, default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    targets = {
        SHARED / "fixtures" / "dashboard_3page.json": gen_fixture(),
        **{SHARED / "fixtures" / f"dashboard_3page_{p['build']}.json": gen_fixture(name)
           for name, p in _builds() if p["layout"] != "layout.json"},
        SHARED / "glcdfont.json": gen_font(a.font),
        ROOT / "firmware" / "LalitStockFirmware" / "shared_contract.h": gen_header(),
    }
    stale = []
    for path, content in targets.items():
        if content is None:
            print(f"skip {path.relative_to(ROOT)} (font source not given and no existing file)")
            continue
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")
    if a.check and stale:
        print("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
